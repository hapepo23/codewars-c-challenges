#include <ctype.h>
#include <stdlib.h>

static int rowcol[50][2] =  // ASCII 46..95: row, col
    {
        {3, 5},    // 46: .
        {4, 7},    // 47: /
        {3, 7},    // 48: 0
        {0, 5},    // 49: 1
        {0, 6},    // 50: 2
        {0, 7},    // 51: 3
        {1, 5},    // 52: 4
        {1, 6},    // 53: 5
        {1, 7},    // 54: 6
        {2, 5},    // 55: 7
        {2, 6},    // 56: 8
        {2, 7},    // 57: 9
        {-1, -1},  // 58: :
        {-1, -1},  // 59: ;
        {-1, -1},  // 60: <
        {-1, -1},  // 61: =
        {-1, -1},  // 62: >
        {-1, -1},  // 63: ?
        {3, 6},    // 64: @
        {0, 0},    // 65: A
        {0, 1},    // 66: B
        {0, 2},    // 67: C
        {0, 3},    // 68: D
        {0, 4},    // 69: E
        {1, 0},    // 70: F
        {1, 1},    // 71: G
        {1, 2},    // 72: H
        {1, 3},    // 73: I
        {1, 4},    // 74: J
        {2, 0},    // 75: K
        {2, 1},    // 76: L
        {2, 2},    // 77: M
        {2, 3},    // 78: N
        {2, 4},    // 79: O
        {3, 0},    // 80: P
        {3, 1},    // 81: Q
        {3, 2},    // 82: R
        {3, 3},    // 83: S
        {3, 4},    // 84: T
        {4, 0},    // 85: U
        {4, 1},    // 86: V
        {4, 2},    // 87: W
        {4, 3},    // 88: X
        {4, 4},    // 89: Y
        {4, 5},    // 90: Z
        {-1, -1},  // 91: [
        {-1, -1},  // 92: B/
        {-1, -1},  // 93: ]
        {-1, -1},  // 94: ^
        {4, 6}     // 95: _
};

int tv_remote(const char* word) {
  int result = 0, r = 0, c = 0;
  while (*word) {
    int index = toupper(*word) - 46;
    int dr = rowcol[index][0], dc = rowcol[index][1];
    result += abs(r - dr) + abs(c - dc) + 1;
    r = dr;
    c = dc;
    word++;
  }
  return result;
}
